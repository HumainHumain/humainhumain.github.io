<section class="qu-est-ce-que-l-ethnographie-accueil">
    <h2>Qu’est-ce que l’ethnographie?</h2>
    <p>L’ethnographie est une méthode de recherche qui s’appuie sur la création d’un lien de qualité avec des informateur.rice.s de premier plan afin de dresser un portrait social d’une organisation ou d’une collectivité.</p>
    <p>Les outils de l’ethnographe sur le terrain sont tirés des sciences sociales et sont d’ordre qualitatif : observation participante, entretiens semi-dirigés, cartographie et conversations informelles. Il s’agit de modes de communication basés sur la confiance et qui permettent l’accès aux dimensions pratiques et symboliques de la réalité des participant.e.s dans leur contexte de vie ou de travail.</p>

